import { jsPDF } from 'jspdf';

/**
 * Generates an official-looking, professional DhanKhoj Claim Discovery Summary PDF
 */
export function generateClaimSummaryPdf({ query, record, matchAnalysis, guidance }) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 16;
  let y = 14;

  // 1. National Tricolor Accent Bar
  doc.setFillColor(255, 153, 51); // Saffron
  doc.rect(margin, y, (pageWidth - margin * 2) / 3, 2.5, 'F');
  doc.setFillColor(240, 240, 240); // White/Gray
  doc.rect(margin + (pageWidth - margin * 2) / 3, y, (pageWidth - margin * 2) / 3, 2.5, 'F');
  doc.setFillColor(19, 136, 8); // Green
  doc.rect(margin + ((pageWidth - margin * 2) / 3) * 2, y, (pageWidth - margin * 2) / 3, 2.5, 'F');

  y += 7;

  // 2. Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(15, 39, 68); // Dark Navy
  doc.text('DhanKhoj — Unclaimed Asset Discovery Summary', margin, y);

  y += 5;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(`Reference ID: DK-${record.id || 'SUMMARY'} | Generated: ${new Date().toLocaleDateString('en-IN', { dateStyle: 'long' })}`, margin, y);

  y += 8;

  // 3. Prominent Disclaimer Callout Box
  doc.setFillColor(254, 243, 199); // Amber 100
  doc.setDrawColor(245, 158, 11); // Amber 500
  doc.roundedRect(margin, y, pageWidth - margin * 2, 14, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(146, 64, 14); // Amber 800
  doc.text('IMPORTANT REGULATORY NOTICE:', margin + 4, y + 5);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  const disclaimerText = 'This document is a discovery and guidance summary generated by DhanKhoj. It is not an official claim form and does not establish ownership. Final verification and payouts must be processed directly through the relevant official institution.';
  const splitDisclaimer = doc.splitTextToSize(disclaimerText, pageWidth - margin * 2 - 8);
  doc.text(splitDisclaimer, margin + 4, y + 9);

  y += 18;

  // 4. Record Overview Grid (2 columns)
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 39, 68);
  doc.text('1. Possible Asset Record Details', margin, y);

  y += 4;
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, y, pageWidth - margin * 2, 38, 2, 2, 'FD');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);

  const col1X = margin + 4;
  const col2X = margin + (pageWidth - margin * 2) / 2 + 2;

  let rowY = y + 6;
  doc.text(`Holder Name:`, col1X, rowY);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text(`${record.holderName}`, col1X + 32, rowY);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);
  doc.text(`Estimated Amount:`, col2X, rowY);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(19, 136, 8); // Green
  doc.text(`Rs. ${Number(record.amount || 0).toLocaleString('en-IN')}`, col2X + 35, rowY);

  rowY += 6;
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);
  doc.text(`Institution / Bank:`, col1X, rowY);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text(`${record.institution}`, col1X + 32, rowY);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);
  doc.text(`Asset Type:`, col2X, rowY);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text(`${record.assetType}`, col2X + 35, rowY);

  rowY += 6;
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);
  doc.text(`Location / City:`, col1X, rowY);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(15, 23, 42);
  doc.text(`${record.location || 'N/A'}`, col1X + 32, rowY);

  doc.setTextColor(71, 85, 105);
  doc.text(`Approx. Year:`, col2X, rowY);
  doc.setTextColor(15, 23, 42);
  doc.text(`${record.approximateYear || 'N/A'}`, col2X + 35, rowY);

  rowY += 6;
  doc.setTextColor(71, 85, 105);
  doc.text(`Claim Authority:`, col1X, rowY);
  doc.setTextColor(15, 23, 42);
  doc.text(`${record.claimAuthority}`, col1X + 32, rowY);

  doc.setTextColor(71, 85, 105);
  doc.text(`Reference/Folio:`, col2X, rowY);
  doc.setTextColor(15, 23, 42);
  doc.text(`${record.sourceReference || 'REF-N/A'}`, col2X + 35, rowY);

  rowY += 6;
  doc.setTextColor(71, 85, 105);
  doc.text(`Confidence Score:`, col1X, rowY);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(14, 116, 144);
  doc.text(`${matchAnalysis?.score || 85}% (${matchAnalysis?.tierLabel || 'Possible Match'})`, col1X + 32, rowY);

  y += 44;

  // 5. Why did DhanKhoj find this? (Explainable AI Breakdown)
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 39, 68);
  doc.text('2. Explainable Match Reasoning', margin, y);

  y += 4;
  doc.setFillColor(241, 245, 249);
  doc.setDrawColor(203, 213, 225);
  doc.roundedRect(margin, y, pageWidth - margin * 2, 26, 2, 2, 'FD');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(51, 65, 85);

  const reasons = matchAnalysis?.reasons || [
    'Name similarity closely matches the holder record.',
    'Institution matches the bank specified.',
    'Approximate year matches timeline provided.'
  ];

  let reasonY = y + 5;
  reasons.slice(0, 4).forEach((r) => {
    doc.text(`• ${r}`, margin + 4, reasonY);
    reasonY += 5;
  });

  y += 32;

  // 6. Recommended Document Checklist
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 39, 68);
  doc.text('3. Common Documents Checklist for Claim Submission', margin, y);

  y += 4;
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('(Check with the institution nodal branch for exact requirements before visiting)', margin, y);

  y += 4;

  const docsList = [
    ...(guidance?.checklists?.standardKyc || []),
    ...(guidance?.checklists?.categorySpecific || []),
    ...(guidance?.checklists?.legalHeirSpecific || [])
  ].slice(0, 6);

  docsList.forEach((d) => {
    doc.setDrawColor(203, 213, 225);
    doc.rect(margin, y, 3, 3); // check box
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(30, 41, 59);
    doc.text(d.name, margin + 5, y + 2.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(`- ${d.description}`, margin + 5, y + 6);

    y += 8;
  });

  y += 3;

  // 7. Step-by-Step Next Steps
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 39, 68);
  doc.text('4. Official Recommended Next Steps', margin, y);

  y += 4;
  const steps = guidance?.steps || [
    { title: 'Step 1: Contact Branch Nodal Officer', action: `Visit the nodal branch of ${record.institution} with this summary.` },
    { title: 'Step 2: Submit Formal KYC & Claim Form', action: 'Submit original/self-attested identity proof, address proof, and passbook.' },
    { title: 'Step 3: Track Direct NEFT/RTGS Settlement', action: 'Official payouts are credited directly to your bank account.' }
  ];

  steps.slice(0, 3).forEach((s, idx) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(15, 39, 68);
    doc.text(`${idx + 1}. ${s.title}`, margin, y);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(71, 85, 105);
    const actionLines = doc.splitTextToSize(s.action, pageWidth - margin * 2 - 4);
    doc.text(actionLines, margin + 4, y + 3.8);
    y += 8;
  });

  // 8. Footer
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(148, 163, 184);
  doc.text('DhanKhoj — Built for Public Financial Empowerment. Free & Open Source. We never charge fees or ask for OTPs.', margin, pageHeight - 8);
  doc.text('Page 1 of 1', pageWidth - margin - 14, pageHeight - 8);

  // Save the PDF file
  const filename = `DhanKhoj_Claim_Summary_${record.holderName.replace(/\s+/g, '_')}_${record.id}.pdf`;
  doc.save(filename);
}
